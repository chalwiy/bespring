def replace(path: Path, mapping: dict[str, str]) -> bool:
    raw = path.read_text(encoding="utf-8")
    out = raw
    for old, new in mapping.items():
        out = out.replace(old, new)
    out = re.sub(
        r">(?:Handle\s+[^<]+?|[^<]+?\s+Handle)\s+under the current SDS<",
        ">المناولة وفق نشرة بيانات السلامة الحالية (SDS)<",
        out,
        flags=re.IGNORECASE,
    )
    if out != raw:
        path.write_text(out, encoding="utf-8")
        return True
    return False


