def replace_text(path: Path, mapping: dict[str, str]) -> bool:
    raw = path.read_text(encoding="utf-8")
    out = raw
    for old, new in mapping.items():
        out = out.replace(old, new)
    out = re.sub(r"(?:условия\s+)+Инкотермс+", "условия Инкотермс", out)
    out = out.replace('"inLanguage":"en"', '"inLanguage":"ru"')
    if out != raw:
        path.write_text(out, encoding="utf-8", newline="")
        return True
    return False

